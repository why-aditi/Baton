// Builds the published handover as a Confluence page in storage format (XHTML).
// Pure: everything it needs is on the Handover, so it is unit-tested without Confluence.
import type { Handover, ScoredItem } from '../types';

const esc = (s: string) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** A real @mention, so new owners get notified when the page is published. */
const mention = (accountId: string) => `<ac:link><ri:user ri:account-id="${esc(accountId)}" /></ac:link>`;

const REASON: Record<Handover['reason'], string> = {
  leaving: 'is leaving',
  leave: 'is going on leave',
  team_change: 'is changing teams',
};

const KIND: Record<ScoredItem['kind'], string> = {
  jira_issue: 'Jira',
  pull_request: 'Pull request',
  confluence_page: 'Page',
  goal: 'Goal',
  project: 'Project',
};

const itemLink = (x: ScoredItem) => `<a href="${esc(x.url)}">${esc(x.key ? `${x.key} ${x.title}` : x.title)}</a>`;

const paragraphs = (text: string) =>
  text
    .split(/\n{2,}/)
    .map((p) => p.trim())
    .filter(Boolean)
    .map((p) => `<p>${esc(p).replace(/\n/g, '<br />')}</p>`)
    .join('');

export const pageTitle = (h: Handover) => `Handover: ${h.subjectName} (last day ${h.lastDay})`;

export const pageBody = (h: Handover): string => {
  const byAri = new Map(h.items.map((x) => [x.ari, x]));
  const out: string[] = [];

  out.push(
    `<p>${mention(h.subjectAccountId)} ${REASON[h.reason]}. Last day: <time datetime="${esc(h.lastDay)}" />. ` +
      `${h.items.length} ${h.items.length === 1 ? 'item' : 'items'}, ${h.items.filter((x) => x.band === 'high').length} high risk.</p>`,
  );

  if (h.summary) {
    out.push('<h2>Overview</h2>', paragraphs(h.summary.overview));
    if (h.summary.risks.length) {
      out.push('<h2>Risks</h2>', `<ul>${h.summary.risks.map((r) => `<li>${esc(r)}</li>`).join('')}</ul>`);
    }
    for (const s of h.summary.sections) {
      out.push(s.ownerAccountId ? `<h2>For ${mention(s.ownerAccountId)}</h2>` : '<h2>Still needs an owner</h2>');
      out.push(paragraphs(s.body));
      const items = s.itemAris.map((a) => byAri.get(a)).filter((x): x is ScoredItem => !!x);
      if (items.length) out.push(`<ul>${items.map((x) => `<li>${itemLink(x)}</li>`).join('')}</ul>`);
    }
  }

  const answered = h.questions.filter((q) => q.answer?.trim());
  if (answered.length) {
    out.push(`<h2>In ${esc(h.subjectName)}'s words</h2>`);
    for (const q of answered) out.push(`<h3>${esc(q.text)}</h3>`, paragraphs(q.answer!));
  }

  if (h.items.length) {
    const rows = h.items
      .map(
        (x) =>
          `<tr><td>${itemLink(x)}</td><td>${KIND[x.kind]}</td><td>${x.risk} (${x.band})</td>` +
          `<td>${esc(x.reasons.join('; '))}</td>` +
          `<td>${x.acceptedOwnerAccountId ? mention(x.acceptedOwnerAccountId) : 'Unassigned'}</td></tr>`,
      )
      .join('');
    out.push(
      '<h2>Everything in this handover</h2>',
      `<table><tbody><tr><th>Item</th><th>Type</th><th>Risk</th><th>Why</th><th>New owner</th></tr>${rows}</tbody></table>`,
    );
  }

  out.push('<p><em>Generated by Baton.</em></p>');
  return out.join('');
};
